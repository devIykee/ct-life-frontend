using System.IO;
using System.Linq;
using System.Security;
using Newtonsoft.Json.Linq;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace CTLife.EditorTools
{
    /// <summary>
    /// Push config for Android builds (2026-10-24). If <c>client/google-services.json</c> exists (Firebase console → the Android
    /// app → download), its values for this build's package become Android resources in CTPush.androidlib
    /// (<c>src/main/res/values/ctpush_firebase.xml</c>, git-ignored): the same names the google-services Gradle plugin writes,
    /// which FirebaseApp reads at start. Without the file that resource is removed and push stays off in the build.
    /// </summary>
    public sealed class PushConfigBuild : IPreprocessBuildWithReport
    {
        public int callbackOrder => 0;
        private static string Json => Path.GetFullPath(Path.Combine(Application.dataPath, "..", "google-services.json"));
        private const string Values = "Assets/Plugins/Android/CTPush.androidlib/src/main/res/values/ctpush_firebase.xml";

        public void OnPreprocessBuild(BuildReport report)
        {
            if (report.summary.platform != BuildTarget.Android) return;
            Write(PlayerSettings.GetApplicationIdentifier(UnityEditor.Build.NamedBuildTarget.Android));
        }

        [MenuItem("CT Life/Retention/Write Push Config")]
        public static void WriteNow() => Write(PlayerSettings.GetApplicationIdentifier(UnityEditor.Build.NamedBuildTarget.Android));

        public static void Write(string package)
        {
            var path = Path.GetFullPath(Path.Combine(Application.dataPath, "..", Values));
            if (!File.Exists(Json))
            {
                if (File.Exists(path)) File.Delete(path);
                Debug.Log("CTLIFE [push] no client/google-services.json: push is disabled in this build");
                return;
            }
            var j = JObject.Parse(File.ReadAllText(Json));
            var project = j["project_info"];
            var client = (j["client"] as JArray)?.FirstOrDefault(c => (string)c["client_info"]?["android_client_info"]?["package_name"] == package);
            if (client == null) throw new BuildFailedException($"google-services.json has no Android app for {package}: add it in the Firebase console");
            string appId = (string)client["client_info"]?["mobilesdk_app_id"];
            string apiKey = (string)(client["api_key"] as JArray)?.FirstOrDefault()?["current_key"];
            string sender = (string)project?["project_number"], projectId = (string)project?["project_id"], bucket = (string)project?["storage_bucket"];
            if (string.IsNullOrEmpty(appId) || string.IsNullOrEmpty(apiKey) || string.IsNullOrEmpty(sender) || string.IsNullOrEmpty(projectId))
                throw new BuildFailedException("google-services.json is missing mobilesdk_app_id, api_key, project_number or project_id");
            string S(string name, string v) => v == null ? "" : $"  <string name=\"{name}\" translatable=\"false\">{SecurityElement.Escape(v)}</string>\n";
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by PushConfigBuild from client/google-services.json. Do not edit. -->\n<resources>\n" +
                S("google_app_id", appId) + S("google_api_key", apiKey) + S("gcm_defaultSenderId", sender) + S("project_id", projectId) +
                S("google_storage_bucket", bucket) + "</resources>\n");
            Debug.Log($"CTLIFE [push] Firebase config for {package} (project {projectId}) written: push is on in this build");
        }
    }
}
