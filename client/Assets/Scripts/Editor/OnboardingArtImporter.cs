using System;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace CTLife.EditorTools
{
    /// <summary>
    /// Import settings for the first-time flow art in Resources/UI/Onboarding (art/LICENSES.md "Onboarding"), applied on
    /// every import so they never depend on hand-edited .meta files. Sizes are chosen for the Seeker (2670×1200) and the APK
    /// budget: no mipmaps (UI), clamp, Android ASTC.
    ///   origin-*.png (640×880 cards, shown ≤ 680 px tall): ASTC 6x6, max 1024 (kept at 640×880): ~0.25 MB each.
    ///   tribe-*.png (512² badges, shown ≤ 140 px): capped at 256, ASTC 5x5 (sharper outlines): ~42 KB each.
    ///   onboarding-bg.png (the title painting pre-blurred and dimmed, generated by <see cref="BuildBackdrop"/>): 1280×576,
    ///   ASTC 8x8 (a blurred image has no detail to lose): ~0.18 MB. The blur is baked, so nothing blurs at runtime.
    /// Also Resources/UI/Kit (soft-glow.png, a 128² white radial alpha falloff written by a few lines of Python with zlib,
    /// see docs/progress/onboarding-ui.md): ASTC 4x4, 16 KB. Resources/UI/Kit/Icons (the glossy icon set, KitIcons): max 128,
    /// ASTC 6x6, about 7 KB each. Resources/UI/Customizer/Portraits (baked base-model portraits, 160×200): ASTC 6x6, ~14 KB each.
    /// </summary>
    public sealed class OnboardingArtImporter : AssetPostprocessor
    {
        public const string Folder = "Assets/Resources/UI/Onboarding/";
        public const string KitFolder = "Assets/Resources/UI/Kit/";
        public const string PortraitFolder = "Assets/Resources/UI/Customizer/";
        public const string BackdropPath = Folder + "onboarding-bg.png";
        private const string TitleArt = "Assets/Resources/UI/Title/title-bg.png";
        public const int BackdropWidth = 1280, BackdropHeight = 576;

        private void OnPreprocessTexture()
        {
            bool kit = assetPath.StartsWith(KitFolder, StringComparison.Ordinal);
            bool portrait = assetPath.StartsWith(PortraitFolder, StringComparison.Ordinal);
            bool illustration = assetPath.StartsWith(PortraitFolder + "Illustrations/", StringComparison.Ordinal);
            bool icon = assetPath.StartsWith(KitFolder + "Icons/", StringComparison.Ordinal);
            if ((!kit && !portrait && !assetPath.StartsWith(Folder, StringComparison.Ordinal)) || !(assetImporter is TextureImporter ti)) return;
            string file = Path.GetFileName(assetPath);
            bool backdrop = file.StartsWith("onboarding-bg", StringComparison.Ordinal);
            bool badge = file.StartsWith("tribe-", StringComparison.Ordinal);
            ti.textureType = TextureImporterType.Default;
            ti.textureShape = TextureImporterShape.Texture2D;
            ti.mipmapEnabled = false;
            ti.npotScale = TextureImporterNPOTScale.None;
            ti.wrapMode = TextureWrapMode.Clamp;
            ti.filterMode = FilterMode.Bilinear;
            ti.alphaIsTransparency = !backdrop;
            ti.alphaSource = backdrop ? TextureImporterAlphaSource.None : TextureImporterAlphaSource.FromInput;
            int max = kit ? 128 : illustration ? 512 : portrait ? 256 : badge ? 256 : backdrop ? 2048 : 1024;
            ti.maxTextureSize = max;
            var android = ti.GetPlatformTextureSettings("Android");
            android.overridden = true;
            android.maxTextureSize = max;
            android.format = icon || portrait ? TextureImporterFormat.ASTC_6x6 : kit ? TextureImporterFormat.ASTC_4x4 : badge ? TextureImporterFormat.ASTC_5x5
                : backdrop ? TextureImporterFormat.ASTC_8x8 : TextureImporterFormat.ASTC_6x6;
            ti.SetPlatformTextureSettings(android);
        }

        /// <summary>
        /// Builds onboarding-bg.png from the approved title painting: downsampled to 1280×576, a three-pass box blur
        /// (≈ Gaussian, σ ≈ 7 px at that size, so ≈ 21 px on the 3840 px original), 16% darker and 8% less saturated, so the
        /// cream-and-plum text and the cards read on it. Menu: CT Life → Onboarding → Build blurred backdrop.
        /// </summary>
        [MenuItem("CT Life/Onboarding/Build blurred backdrop")]
        public static void BuildBackdrop()
        {
            var src = Path.GetFullPath(TitleArt);
            if (!File.Exists(src)) { Debug.LogError("CTLIFE [onboarding-art] missing " + TitleArt); return; }
            var full = new Texture2D(2, 2, TextureFormat.RGBA32, false, false);
            if (!full.LoadImage(File.ReadAllBytes(src), false)) { Debug.LogError("CTLIFE [onboarding-art] could not decode " + TitleArt); return; }
            int w = BackdropWidth, h = BackdropHeight;
            var px = new Color[w * h];
            // Area-average downsample (the source is 3x larger): every output pixel averages its 3x3 source block.
            int sx = full.width / w, sy = full.height / h;
            var fullPx = full.GetPixels();
            for (int y = 0; y < h; y++)
                for (int x = 0; x < w; x++)
                {
                    Color sum = default;
                    int n = 0;
                    int x0 = Mathf.Min(full.width - 1, Mathf.FloorToInt((x + 0.5f) * full.width / w) - sx / 2);
                    int y0 = Mathf.Min(full.height - 1, Mathf.FloorToInt((y + 0.5f) * full.height / h) - sy / 2);
                    for (int j = 0; j < Mathf.Max(1, sy); j++)
                        for (int i = 0; i < Mathf.Max(1, sx); i++)
                        {
                            int fx = Mathf.Clamp(x0 + i, 0, full.width - 1), fy = Mathf.Clamp(y0 + j, 0, full.height - 1);
                            sum += fullPx[fy * full.width + fx];
                            n++;
                        }
                    px[y * w + x] = sum / n;
                }
            UnityEngine.Object.DestroyImmediate(full);
            for (int pass = 0; pass < 3; pass++)
            {
                BoxBlur(px, w, h, 7, true);
                BoxBlur(px, w, h, 7, false);
            }
            for (int i = 0; i < px.Length; i++)
            {
                var c = px[i];
                float luma = c.r * 0.299f + c.g * 0.587f + c.b * 0.114f;
                c = Color.Lerp(c, new Color(luma, luma, luma), 0.08f) * 0.84f;
                c.a = 1f;
                px[i] = c;
            }
            var outTex = new Texture2D(w, h, TextureFormat.RGB24, false, false);
            outTex.SetPixels(px);
            outTex.Apply(false, false);
            Directory.CreateDirectory(Path.GetFullPath(Folder));
            File.WriteAllBytes(Path.GetFullPath(BackdropPath), outTex.EncodeToPNG());
            UnityEngine.Object.DestroyImmediate(outTex);
            AssetDatabase.ImportAsset(BackdropPath, ImportAssetOptions.ForceUpdate);
            Debug.Log("CTLIFE [onboarding-art] wrote " + BackdropPath + " (" + w + "x" + h + ")");
        }

        /// <summary>Separable box blur with a running sum (clamped edges).</summary>
        private static void BoxBlur(Color[] px, int w, int h, int r, bool horizontal)
        {
            int len = horizontal ? w : h, lines = horizontal ? h : w;
            var line = new Color[len];
            float inv = 1f / (2 * r + 1);
            for (int l = 0; l < lines; l++)
            {
                for (int i = 0; i < len; i++) line[i] = px[horizontal ? l * w + i : i * w + l];
                Color acc = default;
                for (int k = -r; k <= r; k++) acc += line[Mathf.Clamp(k, 0, len - 1)];
                for (int i = 0; i < len; i++)
                {
                    px[horizontal ? l * w + i : i * w + l] = acc * inv;
                    acc += line[Mathf.Min(len - 1, i + r + 1)] - line[Mathf.Max(0, i - r)];
                }
            }
        }

        /// <summary>Batch entry: Unity -batchmode -quit -projectPath client -executeMethod CTLife.EditorTools.OnboardingArtImporter.BuildBackdropBatch</summary>
        public static void BuildBackdropBatch()
        {
            int code = 0;
            try { BuildBackdrop(); }
            catch (Exception e) { Debug.LogException(e); code = 1; }
            EditorApplication.Exit(code);
        }
    }
}
