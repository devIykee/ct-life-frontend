        public static bool Has(string key) => key != null && En.ContainsKey(key);

        public static string T(string key) => key != null && En.TryGetValue(key, out var v) ? v : key ?? "";

        public static string F(string key, params object[] args)
        {
            var fmt = T(key);
            try { return string.Format(CultureInfo.InvariantCulture, fmt, args ?? Array.Empty<object>()); }
            catch (FormatException) { return fmt; }
        }

        /// <summary>"beef_cabal_is_real" becomes "Beef cabal is real". The fallback for ids this build has no copy for.</summary>
        public static string Readable(string id)
        {
            if (string.IsNullOrEmpty(id)) return "-";
            var s = new string(id.Select(c => c == '_' || c == '-' ? ' ' : c).Take(40).ToArray()).Trim();
            return s.Length == 0 ? "-" : char.ToUpperInvariant(s[0]) + s.Substring(1);
        }

        public static IEnumerable<string> Keys => En.Keys;
