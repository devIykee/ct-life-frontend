        /// <summary>A bet's question from its outcome id: known ids have copy, others read as words ("sol-1h-up" → "Sol 1h up").</summary>
        public static string PredictionQuestion(string outcomeId)
        {
            if (string.IsNullOrEmpty(outcomeId)) return "—";
            var key = "predict.q." + outcomeId;
            if (T(key) != key) return T(key);
            var words = outcomeId.Replace('-', ' ').Replace('_', ' ').Trim();
            return words.Length == 0 ? outcomeId : char.ToUpperInvariant(words[0]) + words.Substring(1);
        }

        public static string T(string key) => key != null && Copy.TryGetValue(key, out var s) ? NameTable.Apply(s) : key ?? "";

        public static string F(string key, params object[] args)
        {
            try { return string.Format(CultureInfo.InvariantCulture, T(key), args ?? new object[0]); }
            catch (System.FormatException) { return T(key); }
        }

        /// <summary>The message for a classified failure.</summary>
        public static string Err(MoneyError e) => e == null ? "" : F(e.Key ?? "err.generic", e.Args);

        public static bool Has(string key) => key != null && Copy.ContainsKey(key);
    }
