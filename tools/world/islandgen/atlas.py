"""CT Island v2 map atlas (World lane): the painted island for the map and minimap, and atlas.json version 2.

Paints the island from the same data that builds it (heightfield relief, water, forests, fields, parks, roads, junctions,
and the dress.json buildings) with render.plan_image (no labels), and writes where every venue's baked area map sits on
it. Atlas metres ARE island metres (x east, y = island z north), so the minimap centres on the player's world position.

Run (repo root), after islandgen.py and dress.py:
  uv run --no-project --with pillow==12.3.0 --with scipy==1.18.1 --with numpy==2.4.2 python -I tools/world/islandgen/atlas.py
Writes client/Assets/Resources/UI/Map/Atlas/ct-island.png and client/Assets/Resources/UI/Map/atlas.json.

atlas.json v2 (same shape as v1; the map UI reads it unchanged):
  areas[]: origin = the venue root on the island; rotationDeg = the venue yaw (degrees clockwise seen from above, the
           root's eulerAngles.y); rotation = -rotationDeg (v1 field: counter-clockwise); scale 1; center = where the
           area's centre lands; plot = the district.
  plots[]: the districts (kind "district"); plotSize is the size the map UI frames when a district is picked, and its
           name pill rides plotSize / 2 + 6 m north of center, so center is set that far south of the label point.
"""
import json
import math
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import numpy as np
from PIL import Image
from scipy import ndimage

import geom as G
import islandgen as IG
import layout as L
import network as NW
import render
import terrain as T

REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
OUT = os.path.join(HERE, 'out')
MAP = os.path.join(REPO, 'client', 'Assets', 'Resources', 'UI', 'Map')
SIZE = 2048
MIN = (-1024.0, -1024.0)
SPAN = 2048.0
PLOT_SIZE = 240.0


def main():
    t0 = time.time()
    # the same pipeline as islandgen (deterministic), up to the carved heightfield
    coast, ctypes, ccliff = T.coastline()
    land = T.land_mask(coast)
    inland = ndimage.distance_transform_edt(land) * L.CELL
    seaward = ndimage.distance_transform_edt(~land) * L.CELL
    emaps = {}
    nat, coastw = T.natural_heights(land, inland, seaward, coast, ctypes, ccliff, stats=emaps)
    T.fit_water_levels(nat)
    river = T.river_samples()
    net = NW.Network()
    net.build_routes(nat, T.sample)
    net.make_roundabouts()
    net.solve_heights(nat, T.sample, river)
    net.build_junctions()
    net.lane_graph()
    t = json.load(open(os.path.join(OUT, 'terrain.json')))
    raw = np.fromfile(os.path.join(OUT, 'height.r16'), dtype='<u2').reshape(t['samples'], t['samples']).astype(np.float64)
    h = t['hmin'] + raw / 65535.0 * (t['hmax'] - t['hmin'])
    _, river = T.carve_river(nat, land)
    forest = np.asarray(Image.open(os.path.join(OUT, 'forest.png')), dtype=np.float64)[::-1] / 255.0
    plan = json.load(open(os.path.join(OUT, 'plan.json')))
    dress_path = os.path.join(OUT, 'dress.json')
    buildings = json.load(open(dress_path))['buildingBoxes'] if os.path.exists(dress_path) else []
    os.makedirs(os.path.join(MAP, 'Atlas'), exist_ok=True)
    view = (MIN[0], MIN[1], MIN[0] + SPAN, MIN[1] + SPAN)
    png = os.path.join(MAP, 'Atlas', 'ct-island.png')
    render.plan_image(h, land, net, plan['venues'], plan['homes'], river, forest, png, view=view, ppm=SIZE / SPAN, annotate=False,
                      buildings=buildings, size=(SIZE, SIZE))
    # placements: every area that has a baked map and a place on the island
    areas = json.load(open(os.path.join(MAP, 'areas.json')))['areas']
    by_id = {a['id']: a for a in areas}
    placed = []
    for v in plan['venues'] + plan['homes']:
        a = by_id.get(v['id'])
        if a is None:
            continue
        mn, sz = a['min'], a['size']
        cx, cz = G.local_to_world(v['origin'][0], v['origin'][2], v['yaw'], mn[0] + sz[0] / 2, mn[1] + sz[1] / 2)
        placed.append(dict(id=v['id'], plot=v['district'], origin=[round(v['origin'][0], 3), round(v['origin'][2], 3)],
                           rotationDeg=round(v['yaw'] % 360.0, 3), rotation=round(-(v['yaw'] % 360.0), 3), scale=1,
                           center=[round(cx, 3), round(cz, 3)], elevation=round(v['origin'][1], 3)))
    plots = []
    for d in L.DISTRICTS:
        if d['id'] == 'islet':
            continue                      # no venue there; the islet shows on the painted map
        lx, lz = d['label']
        plots.append(dict(id=d['id'], name=d['name'], kind='district', center=[lx, round(lz - (PLOT_SIZE / 2 + 6.0), 3)],
                          label=[lx, lz]))
    doc = dict(
        version=2, name='CT Island',
        note='Generated by tools/world/islandgen/atlas.py from the CT Island v2 world data. Atlas metres = island metres '
             '(x east, y = island z north); uv = (p - min) / size. An area\'s venue-local point (x, z) lands at '
             'origin + R(rotation) * (x, z) * scale, rotation counter-clockwise; rotationDeg (= -rotation) is the venue '
             'yaw, clockwise seen from above. Plots are the districts; a district\'s name pill rides plotSize / 2 + 6 m '
             'north of its center (its label point).',
        texture='UI/Map/Atlas/ct-island', min=list(MIN), size=[SPAN, SPAN], pixels=[SIZE, SIZE], plotSize=PLOT_SIZE,
        plots=plots, areas=placed, generated=time.strftime('%Y-%m-%d'))
    json.dump(doc, open(os.path.join(MAP, 'atlas.json'), 'w'), indent=1)
    print(f'[atlas] {png} ({SIZE}x{SIZE}), {len(placed)} areas, {len(plots)} districts ({time.time() - t0:.1f}s)', flush=True)


if __name__ == '__main__':
    main()
