def draw(img, x, y, text, scale=2, color=(0.1, 0.1, 0.12)):
    """Draw text into float image array img (H, W, C>=3), top-left at (x, y)."""
    cx = x
    for ch in text.upper():
        g = _G.get(ch, _G[' '])
        for r, row in enumerate(g):
            for c, bit in enumerate(row):
                if bit == '1':
                    y0, x0 = y + r * scale, cx + c * scale
                    if 0 <= y0 < img.shape[0] - scale and 0 <= x0 < img.shape[1] - scale:
                        img[y0:y0 + scale, x0:x0 + scale, :3] = color
        cx += 6 * scale
    return cx
