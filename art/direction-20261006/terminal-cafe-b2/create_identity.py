"""Original decorative café artwork; no scraped artwork, prices or live data.

Run with Pillow. Only raster glyphs are distributed; installed fonts are not copied.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import hashlib, json

HERE = Path(__file__).resolve().parent
TEX = HERE / "Textures"
TEX.mkdir(exist_ok=True)
FONT = Path("/System/Library/Fonts/Supplemental")
INK, CREAM, GOLD = (41, 61, 57), (237, 226, 202), (160, 119, 70)

def font(size, bold=False):
    return ImageFont.truetype(str(FONT / ("Arial Bold.ttf" if bold else "Arial.ttf")), size)

def centered(draw, text, y, size, fill=INK, bold=False, width=1024):
    f = font(size, bold)
    box = draw.textbbox((0, 0), text, font=f)
    draw.text(((width - box[2]) / 2, y), text, font=f, fill=fill)

im = Image.new("RGB", (1024, 448), CREAM)
d = ImageDraw.Draw(im)
d.rectangle((18, 18, 1005, 429), outline=GOLD, width=2)
centered(d, "TERMINAL CAFÉ", 37, 24)
centered(d, "NO ALPHA.", 101, 101, bold=True)
centered(d, "JUST COFFEE.", 222, 101, bold=True)
d.line((427, 379, 597, 379), fill=GOLD, width=3)
im.save(TEX / "CafeIdentity.png")

im = Image.new("RGB", (640, 896), INK)
d = ImageDraw.Draw(im)
d.rectangle((19, 19, 620, 876), outline=GOLD, width=3)
centered(d, "THE USUAL", 78, 57, CREAM, True, 640)
d.line((80, 191, 560, 191), fill=GOLD, width=3)
for text, y in [("Espresso", 266), ("Flat white", 372), ("Filter coffee", 478), ("Something sweet", 584)]:
    centered(d, text, y, 43, CREAM, width=640)
centered(d, "Stay for the conversation.", 759, 26, CREAM, width=640)
im.save(TEX / "CafeMenu.png")

# A calm screensaver, not a pretend trading terminal or an invented app state.
im = Image.new("RGB", (1024, 592), INK)
d = ImageDraw.Draw(im)
d.ellipse((372, 421, 652, 451), fill=(28, 47, 43))
d.rounded_rectangle((397, 203, 607, 420), radius=30, fill=CREAM)
d.ellipse((560, 248, 671, 357), outline=CREAM, width=19)
d.ellipse((409, 216, 595, 259), fill=(113, 77, 46))
for x in (458, 507, 556):
    d.arc((x - 16, 116, x + 16, 191), 250, 80, fill=GOLD, width=5)
centered(d, "TERMINAL CAFÉ", 508, 22, CREAM)
im.save(TEX / "CafeDesktop.png")

(HERE / "artwork-provenance.json").write_text(json.dumps({
    "source": "Original project-authored typography and vector-like shapes generated by create_identity.py",
    "meaning": "Decorative café identity, menu without prices, and static coffee screensaver; no market claims or live service state",
    "font": "Rasterized locally installed Arial / Arial Bold; no font files included",
    "files": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(TEX.glob("*.png"))}
}, indent=2) + "\n")
